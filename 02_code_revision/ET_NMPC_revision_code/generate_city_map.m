function buildings = generate_city_map()
% =========================================================================
% generate_city_map.m
%
% 15 个静态建筑物的三维城市峡谷地图
%
% 设计目标：
% 1. 保持静态建筑物数量为 15 个；
% 2. 长方体、圆柱体、圆锥体三类障碍物均匀出现；
% 3. 主航路附近同时存在不同形状障碍物；
% 4. 避免中途出现大面积空白区域；
% 5. 建筑物高度不完全相同，形成更真实的城市峡谷环境；
% 6. 保留可行通道，使无人机需要侧绕、局部爬升和动态避障。
%
% 建筑物类型：
% type = 1 ：长方体建筑物 Cuboid
% type = 2 ：圆柱体建筑物 Cylinder
% type = 3 ：圆锥体建筑物 Cone
%
% 每一行 b_data 的含义：
% [x, y, w, l, h, type]
%
% x, y ：建筑物中心位置，单位 m
% w    ：宽度，单位 m
% l    ：长度，单位 m
% h    ：高度，单位 m
% type ：建筑物类型
% =========================================================================


%% ========================================================================
% 1. 建筑物数据
% ========================================================================
% 默认任务：
% 起点：[0, 0, 3]
% 终点：[40, 40, 12]
%
% 分布原则：
% - 沿名义路径两侧交错放置障碍物；
% - 中段增加长方体建筑物，避免全部是圆柱和圆锥；
% - 主航线附近有障碍物，但不完全封死；
% - 部分建筑物高度接近或高于目标高度，避免无人机全部从上方飞过。
% ========================================================================

b_data = [

    % =====================================================================
    % A 区：起点附近
    % =====================================================================
    % x,    y,    w,    l,    h,  type

      6,   12,   4.0,  4.0,  11,   1;    % B1：起点左前方长方体
     12,    5,   4.0,  4.0,  10,   2;    % B2：起点右前方圆柱体
      5,   25,   4.4,  4.4,  13,   3;    % B3：左侧背景圆锥体


    % =====================================================================
    % B 区：中前段，构成第一段 S 型绕行
    % =====================================================================

     14,   17,   3.8,  3.8,  12,   2;    % B4：主航路附近圆柱体
     15,   30,   4.2,  4.0,  14,   1;    % B5：中前段左侧长方体
     23,   14,   4.0,  4.0,  13,   3;    % B6：中前段右侧圆锥体
     10,   36,   4.4,  4.4,  12,   2;    % B7：左上背景圆柱体


    % =====================================================================
    % C 区：核心区域，补充中段空白并混合三类建筑物
    % =====================================================================

     20,   21,   3.8,  4.2,  13,   1;    % B8：核心区长方体，补充主航路中段
     26,   23,   3.8,  3.8,  14,   2;    % B9：核心区圆柱体，填补中段空白
     22,   31,   4.0,  4.0,  15,   3;    % B10：左上核心圆锥体
     31,   18,   4.2,  3.8,  13,   1;    % B11：右侧核心长方体
     36,   28,   3.8,  3.8,  14,   3;    % B12：右上核心圆锥体


    % =====================================================================
    % D 区：终点附近
    % =====================================================================

     32,   35,   3.8,  3.8,  13,   2;    % B13：终点前圆柱体
     42,   30,   4.0,  4.2,  12,   1;    % B14：终点右下长方体
     30,   42,   4.0,  4.0,  12,   2     % B15：终点左上圆柱体
];

%% ========================================================================
% 2. 转换为结构体数组
% ========================================================================

buildings = struct([]);

for i = 1:size(b_data, 1)

    b.x = b_data(i, 1);
    b.y = b_data(i, 2);
    b.w = b_data(i, 3);
    b.l = b_data(i, 4);
    b.h = b_data(i, 5);
    b.type = b_data(i, 6);

    % 对圆柱体和圆锥体：
    % r 表示底面半径。
    %
    % 对长方体：
    % r 只是辅助字段，真实绘图和碰撞检测仍然使用 w、l。
    b.r = max(b.w, b.l) / 2;

    % 建筑物名称，方便 main_simulation.m 打印碰撞信息
    b.name = ['B', num2str(i)];

    buildings = [buildings, b]; %#ok<AGROW>
end

%% ========================================================================
% 3. 合法性检查
% ========================================================================

if size(b_data, 1) ~= 15
    error('地图错误：b_data 行数不是 15 行。当前行数为 %d。', size(b_data, 1));
end

if length(buildings) ~= 15
    error('地图错误：当前 buildings 数量不是 15 个。当前数量为 %d。', length(buildings));
end

for i = 1:length(buildings)

    if buildings(i).h <= 0
        error('地图错误：第 %d 个建筑物高度必须大于 0。', i);
    end

    if buildings(i).w <= 0 || buildings(i).l <= 0
        error('地图错误：第 %d 个建筑物宽度和长度必须大于 0。', i);
    end

    if ~ismember(buildings(i).type, [1, 2, 3])
        error('地图错误：第 %d 个建筑物类型必须为 1、2 或 3。', i);
    end
end

end